#!/usr/bin/env bash
set -euo pipefail

dir=${1:-dist/release}

test -f "$dir/release.yaml"
test -f "$dir/images.txt"
for group in 00-crds 10-kube-vip 20-fabric 25-multus 30-nmstate 40-rook 41-rook-csi 50-kubevirt 52-aaq 55-velero 60-cert-manager 65-traefik 70-monitoring 71-kube-prometheus-stack 80-kured 86-tenancy 88-proxy 90-bedrock 92-catalog; do
  test -d "$dir/manifests/$group"
done
grep -q 'kind: CustomResourceDefinition' "$dir/manifests/00-crds/cert-manager-crds.yaml"
grep -q 'kind: DaemonSet' "$dir/manifests/10-kube-vip/kube-vip.yaml"
grep -q 'name: fabric' "$dir/manifests/20-fabric/fabric.yaml"
grep -q 'BEDROCK_MASTER_IPS' "$dir/manifests/20-fabric/fabric.yaml"
grep -q 'kind: CustomResourceDefinition' "$dir/manifests/00-crds/fabric-crds.yaml"
grep -q 'kind: DaemonSet' "$dir/manifests/25-multus/multus.yaml"
grep -q 'multus-cni:v4.3.1-thick' "$dir/manifests/25-multus/multus.yaml"
grep -q 'name: network-attachment-definitions.k8s.cni.cncf.io' "$dir/manifests/00-crds/multus-crds.yaml"
if grep -q 'kind: CustomResourceDefinition' "$dir/manifests/25-multus/multus.yaml"; then exit 1; fi
grep -q 'name: nmstate-operator' "$dir/manifests/30-nmstate/nmstate.yaml"
grep -q 'kind: NMState' "$dir/manifests/30-nmstate/nmstate.yaml"
grep -q 'name: nmstates.nmstate.io' "$dir/manifests/00-crds/nmstate-crds.yaml"
grep -q 'kubernetes-nmstate-handler:v0.87.0' "$dir/images.txt"
grep -q 'name: rook-ceph-operator' "$dir/manifests/40-rook/rook.yaml"
grep -q 'name: snapshot-controller' "$dir/manifests/40-rook/rook.yaml"
grep -q 'snapshot-controller:v8.5.0' "$dir/manifests/40-rook/rook.yaml"
grep -q 'name: cephclusters.ceph.rook.io' "$dir/manifests/00-crds/rook-crds.yaml"
grep -q 'name: volumesnapshotclasses.snapshot.storage.k8s.io' "$dir/manifests/00-crds/rook-crds.yaml"
grep -q 'name: drivers.csi.ceph.io' "$dir/manifests/00-crds/rook-crds.yaml"
grep -q 'kind: Driver' "$dir/manifests/41-rook-csi/rook-csi.yaml"
test "$(grep -c 'snapshotPolicy: volumeSnapshot' "$dir/manifests/41-rook-csi/rook-csi.yaml")" -eq 2
grep -q 'name: virt-operator' "$dir/manifests/50-kubevirt/kubevirt.yaml"
grep -q 'name: cdi-operator' "$dir/manifests/50-kubevirt/kubevirt.yaml"
grep -q 'name: kubevirts.kubevirt.io' "$dir/manifests/00-crds/kubevirt-crds.yaml"
grep -q 'name: cdis.cdi.kubevirt.io' "$dir/manifests/00-crds/kubevirt-crds.yaml"
grep -q 'quay.io/kubevirt/virt-launcher:v1.9.0' "$dir/images.txt"
grep -q 'quay.io/ceph/ceph:v20.2.4' "$dir/images.txt"
grep -q 'quay.io/cephcsi/cephcsi:v3.17.1' "$dir/images.txt"
grep -q 'image: quay.io/ceph/ceph:v20.2.4' "$dir/release.yaml"
grep -q 'name: cert-manager' "$dir/manifests/60-cert-manager/cert-manager.yaml"
grep -q 'kind: Service' "$dir/manifests/65-traefik/traefik.yaml"
grep -q 'kube-vip.io/loadbalancerIPs: \${BEDROCK_VIP}' "$dir/manifests/65-traefik/traefik.yaml"
grep -q 'kind: TLSStore' "$dir/manifests/65-traefik/traefik.yaml"
grep -q 'name: ingressroutes.traefik.io' "$dir/manifests/00-crds/traefik-crds.yaml"
grep -q 'endpointslices' "$dir/manifests/10-kube-vip/kube-vip.yaml"
grep -q 'metrics-server' "$dir/manifests/70-monitoring/monitoring.yaml"
grep -q 'kind: DaemonSet' "$dir/manifests/80-kured/kured.yaml"
grep -q 'name: bedrock-operator' "$dir/manifests/90-bedrock/bedrock.yaml"
grep -q 'kind: ValidatingAdmissionPolicy' "$dir/manifests/90-bedrock/bedrock.yaml"
grep -q 'name: bedrock-authn' "$dir/manifests/85-authn/authn.yaml"
grep -q 'kind: ServersTransport' "$dir/manifests/85-authn/authn.yaml"
grep -q 'kind: PodDisruptionBudget' "$dir/manifests/85-authn/authn.yaml"
grep -q 'secretName: bedrock-ca' "$dir/manifests/85-authn/authn.yaml"
grep -q 'name: bedrock:bedrock-admins' "$dir/manifests/85-authn/authn.yaml"
! grep -rq 'ghcr.io/cloudyfolks-io/bedrock:dev' "$dir/manifests" || test "$(grep '^version:' "$dir/release.yaml")" = "version: dev"
grep -q '^images:' "$dir/release.yaml"
grep -q 'quay.io/kubevirt/cirros-container-disk-demo:v1.9.0' "$dir/images.txt"
awk '/^---$/{doc=""} /^kind: DaemonSet$/{doc="ds"} doc=="ds" && /^  name: ovs-ovn$/{doc="ovs"} doc=="ovs" && /^    type: OnDelete$/{found=1} END{exit found ? 0 : 1}' "$dir/manifests/20-fabric/fabric.yaml"
grep -q 'kind: ClusterImage' "$dir/manifests/92-catalog/catalog.yaml"
grep -q 'quay.io/containerdisks/ubuntu:24.04' "$dir/images.txt"
grep -q 'quay.io/containerdisks/debian:13' "$dir/images.txt"
grep -q 'quay.io/containerdisks/almalinux:9' "$dir/images.txt"
grep -q 'quay.io/containerdisks/fedora:43' "$dir/images.txt"
grep -q 'quay.io/kubevirt/virtio-container-disk:v1.9.0' "$dir/images.txt"
grep -q 'name: velero' "$dir/manifests/55-velero/velero.yaml"
grep -q 'name: node-agent' "$dir/manifests/55-velero/velero.yaml"
grep -q 'name: backups.velero.io' "$dir/manifests/00-crds/velero-crds.yaml"
grep -q 'name: datauploads.velero.io' "$dir/manifests/00-crds/velero-crds.yaml"
grep -q 'docker.io/velero/velero-plugin-for-aws:v1.14.4' "$dir/images.txt"
grep -q 'quay.io/kubevirt/kubevirt-velero-plugin:v0.9.1' "$dir/images.txt"
grep -q 'ROOK_OBC_ALLOW_ADDITIONAL_CONFIG_FIELDS: maxObjects,maxSize,bucketMaxObjects,bucketMaxSize,bucketOwner' "$dir/manifests/40-rook/rook.yaml"
test -d "$dir/manifests/addons/kata"
test -d "$dir/manifests/addons/loki"
grep -q 'name: kata-deploy' "$dir/manifests/addons/kata/kata.yaml"
grep -q 'name: alloy' "$dir/manifests/addons/loki/"*.yaml
grep -q 'name: prometheuses.monitoring.coreos.com' "$dir/manifests/00-crds/kube-prometheus-stack-crds.yaml"
grep -q 'grafana/loki:3.7.8' "$dir/images.txt"
grep -q 'quay.io/kubevirt/aaq-operator:v1.8.0' "$dir/images.txt"
echo "check-release passed"
